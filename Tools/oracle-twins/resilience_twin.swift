//   SRC=Packages/StrandAnalytics/Sources/StrandAnalytics
//   swiftc -O -parse-as-library $SRC/ResilienceEngine.swift Tools/oracle-twins/resilience_twin.swift \
//       -o /tmp/resilience_twin && /tmp/resilience_twin \
//       > Packages/StrandAnalytics/Tests/StrandAnalyticsTests/oracles/resilience.json
